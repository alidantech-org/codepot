import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const appRoot = resolve(scriptDirectory, '..');
const workspaceRoot = resolve(appRoot, '../..');
const docsRoot = resolve(workspaceRoot, 'docs');
const output = resolve(appRoot, 'src/generated/docs.ts');

/**
 * Root docs are the only maintained source. This build step embeds their exact
 * text into the Next bundle so standalone and serverless deployments do not
 * need runtime access to files outside apps/site.
 */
const entries = await readdir(docsRoot, { withFileTypes: true });
const documents = {};
for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
  if (!entry.isFile() || !entry.name.endsWith('.md')) continue;
  const slug = entry.name.slice(0, -3);
  documents[slug] = await readFile(resolve(docsRoot, entry.name), 'utf8');
}
const navigation = JSON.parse(await readFile(resolve(docsRoot, 'navigation.json'), 'utf8'));
const source = [
  '// Generated by scripts/sync-docs.mjs. Do not edit.',
  `export const DOCS = ${JSON.stringify(documents, null, 2)} as const;`,
  `export const NAVIGATION = ${JSON.stringify(navigation, null, 2)} as const;`,
  'export type DocSlug = keyof typeof DOCS;',
  '',
].join('\n');
await mkdir(dirname(output), { recursive: true });
await writeFile(output, source, 'utf8');
console.log(`Synced ${Object.keys(documents).length} documentation files.`);
